    " if not okb or type(rb)~='number' then hp_buf_ok=false else hp_digest=rb end",
    'end',
    "if not hp_buf_ok then hp_mesh_seed=hp_u32(hp_bxor(hp_mesh_seed,0xBAD9)) end",
    "if not hp_mesh_edge('buffer',hp_buf_ok,hp_digest,5) then hp_mesh_seed=hp_u32(hp_bxor(hp_mesh_seed,0xBADA)) end",
    // edge 6: math graph (trig)
    'local hp_math_ok=true',
    'local hp_math_link=0',
    'do',
    ' local okm,rm=pcall(function()',
    "  if type(math.pi)~='number' or type(math.sin)~='function' or type(math.cos)~='function' or type(math.sqrt)~='function' then return nil end",
    '  local radius=1.25+hp_band(hp_bxor(hp_mesh_seed,hp_wire_bit(hp_mesh_seed,0x106,true)),0xFF)/128',
    '  local angle=(hp_mesh_seed%6283)/1000',
    '  local circumference=2*math.pi*radius',
    '  local area=math.pi*radius*radius',
    '  if not hp_close(circumference/radius,2*math.pi,1e-12) or not hp_close(area/(radius*radius),math.pi,1e-12) then return nil end',
    '  local g1=math.sin(angle)',
    '  local g2=math.cos(angle)',
    '  local g3=math.sin(angle+math.pi/3)',
    '  local g4=math.cos(angle+math.pi/5)',
    '  local g5=math.sin(angle+math.pi/7)',
    '  for i=1,5 do',
    '   local n1=(g2+g3-g4+g5)/2',
    '   local n2=(g3+g4-g5+g1)/2',
    '   local n3=(g4+g5-g1+g2)/2',
    '   local n4=(g5+g1-g2+g3)/2',
    '   local n5=(g1+g2-g3+g4)/2',
    '   g1,g2,g3,g4,g5=n1,n2,n3,n4,n5',
