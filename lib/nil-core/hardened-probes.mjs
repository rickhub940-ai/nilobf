    // A successful mesh leaves the pad unchanged; any failed edge poisons it.
    'hp=(not hp_failed and hp_mesh_count==7 and hp_final_ok) and 0 or hp_bor(hp_bxor(hp_mesh_seed,hp_mesh_hash),1)',
    'end)',
    'if not hp_call_ok then hp=1 end',
