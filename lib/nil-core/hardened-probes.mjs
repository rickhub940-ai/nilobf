    '   local position=(i*17+29)%size',
    '   buffer.writeu8(buf,position,value)',
    '  end',
    '  for position=0,size-1 do',
    '   local source=((position-29)*241)%size',
    '   if buffer.readu8(buf,position)~=data[source+1] then return nil end',
    '  end',
    '  local raw=buffer.tostring(buf)',
    "  if type(raw)~='string' or #raw~=size then return nil end",
    '  local clone=buffer.fromstring(raw)',
    '  if buffer.len(clone)~=size or buffer.tostring(clone)~=raw then return nil end',
    '  a=hp_u32(hp_bxor(hp_mesh_seed,hp_env_key))',
    '  b=hp_u32(hp_bxor(hp_bxor(hp_mesh_seed,0x6D2B79F1),hp_env_key))',
    '  c=hp_u32(hp_bxor(hp_bor(hp_mesh_seed,0x3C6EF372),hp_env_key))',
    '  d=hp_u32(hp_bxor(hp_bxor(hp_mesh_seed,0xDAA66D2B),hp_env_key))',
    '  e=hp_u32(hp_bxor(hp_bor(hp_mesh_seed,0xBB67AE85),hp_env_key))',
    '  for i=0,size-1 do',
    '   local position=(i*17+29)%size',
    '   local feed=hp_u32(hp_bxor(buffer.readu8(clone,position)+i*257,hp_env_key))',
