    '   local old_ok,old_env=pcall(getfenv,fn)',
    '   local set_ok=pcall(setfenv,fn,env)',
    "   if not old_ok or type(old_env)~='table' or not set_ok then return false end",
    '   bound[#bound+1]={fn=fn,env=old_env}',
    '   return true',
    '  end',
    '  local proxy_bound=bind_env(proxy_index,proxy_env) and bind_env(proxy_newindex,proxy_env) and bind_env(proxy_call,proxy_env) and bind_env(proxy_eq,proxy_env)',
