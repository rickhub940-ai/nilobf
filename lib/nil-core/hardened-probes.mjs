    '  local result=math.abs(graph_cross+graph_norm)*1000000',
    '  return hp_u32(math.floor(result))',
    ' end)',
    " if not okm or type(rm)~='number' then hp_math_ok=false else hp_math_link=rm end",
    'end',
    "if not hp_math_ok then hp_mesh_seed=hp_u32(hp_bxor(hp_mesh_seed,0xBADB)) end",
    "if not hp_mesh_edge('math',hp_math_ok,hp_math_link,6) then hp_mesh_seed=hp_u32(hp_bxor(hp_mesh_seed,0xBADC)) end",
    // edge 7: atom proxy (pass/fail letters)
    'local hp_atom_ok=true',
    'local hp_atom_link=0',
    'do',
    ' local okp,rp,linkp=pcall(function()',
    '  local shadows={}',
    '  local proxy_nodes={}',
    '  local rawget,rawset,type,rawequal=rawget,rawset,type,rawequal',
    '  local global_proxy',
    '  local proxy_index=function(self,key)',
